#!/usr/bin/env node
/**
 * Take a robot rig drop's numbers into the repo (2026-09-30: Peep v15, Magnet v2).
 *
 *   node tools/peep-rig-sync.mjs [drop-dir]            # Peep
 *   node tools/peep-rig-sync.mjs magnet [drop-dir]     # Magnet: src/magnet/, magnetrig.*
 *   node tools/peep-rig-sync.mjs periscope [drop-dir]  # Periscope: src/periscope/, periscoperig.*
 *
 * The drop (default `codex_output/peep-animations-v15`, not checked in) holds
 * the authoritative rig as JavaScript: `tools/rig.mjs`, `tools/animations.mjs`
 * and `tools/collision-hulls.mjs`. `src/peep/rig.ts` is a hand port of the
 * first two. This writes:
 *
 * - `src/peep/hulls.ts`: the fall-apart contact hulls, as data.
 * - `services/battle-royale-server/src/utils/peeprig.fixtures.json`: poses
 *   sampled from the drop's own modules, which `peeprig.spec.ts` checks the
 *   port against. A new drop that changes a number fails that spec until the
 *   port is updated to match.
 *
 * The art goes separately, through `tools/bake-peep-atlas.py`.
 */
import { writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const client = join(here, '..')
// Peep is the default, so the old one-argument form still means Peep.
const ROBOTS = {
  peep: { drop: 'peep-animations-v15', src: 'peep', fixtures: 'peeprig.fixtures.json', label: 'Peep' },
  magnet: { drop: 'magnet-animations-v2', src: 'magnet', fixtures: 'magnetrig.fixtures.json', label: 'Magnet' },
  periscope: { drop: 'periscope-animations-v1', src: 'periscope', fixtures: 'periscoperig.fixtures.json', label: 'Periscope' }
}
const named = ROBOTS[process.argv[2]] !== undefined
const robot = ROBOTS[named ? process.argv[2] : 'peep']
const drop = resolve((named ? process.argv[3] : process.argv[2]) ?? join(client, 'codex_output', robot.drop))
const load = (file) => import(pathToFileURL(join(drop, 'tools', file)).href)

const { collisionHulls } = await load('collision-hulls.mjs')
const { animationPose, clips } = await load('animations.mjs')
const rig = await load('rig.mjs')

/**
 * Where the drop's own Canvas drawing puts each image's four corners, in rig
 * units (y up): `drawPose` run against a context that only records its matrix
 * at each drawImage. The spec checks `regionMatrix` / `eyeMatrix` against it.
 */
function drawnCorners (state, matrices) {
  const mul = (p, q) => [p[0] * q[0] + p[2] * q[1], p[1] * q[0] + p[3] * q[1], p[0] * q[2] + p[2] * q[3], p[1] * q[2] + p[3] * q[3], p[0] * q[4] + p[2] * q[5] + p[4], p[1] * q[4] + p[3] * q[5] + p[5]]
  let cur = [1, 0, 0, 1, 0, 0]
  const stack = []
  const out = []
  const noop = () => {}
  const ctx = {
    save: () => stack.push(cur),
    restore: () => { cur = stack.pop() },
    translate: (x, y) => { cur = mul(cur, [1, 0, 0, 1, x, y]) },
    scale: (x, y) => { cur = mul(cur, [x, 0, 0, y, 0, 0]) },
    rotate: (r) => { cur = mul(cur, [Math.cos(r), Math.sin(r), -Math.sin(r), Math.cos(r), 0, 0]) },
    transform: (a, b, c, d, e, f) => { cur = mul(cur, [a, b, c, d, e, f]) },
    drawImage: (img, x, y, w, h) => {
      // Undo drawPose's outer scale(1, -1) so the corners are in rig space.
      const m = mul([1, 0, 0, -1, 0, 0], cur)
      const pts = []
      for (const [u, v] of [[x, y], [x + w, y], [x + w, y + h], [x, y + h]]) pts.push(m[0] * u + m[2] * v + m[4], m[1] * u + m[3] * v + m[5])
      out.push(pts)
    },
    // Periscope clips its eye to an ellipse; the clip doesn't move anything.
    beginPath: noop, moveTo: noop, bezierCurveTo: noop, closePath: noop, clip: noop, ellipse: noop, globalAlpha: 1
  }
  rig.drawPose(ctx, new Proxy({}, { get: () => ({}) }), state, matrices, 0, 0, 1, {})
  return out
}

writeFileSync(join(client, 'src', robot.src, 'hulls.ts'),
  '/* eslint-disable */\n' +
  `// Generated by tools/peep-rig-sync.mjs from the ${robot.label} drop's collision-hulls.mjs:\n` +
  '// contact silhouettes derived from the art\'s alpha, for the fall-apart clip.\n' +
  '// Do not edit; re-run the tool on a new drop.\n' +
  'export const HULLS: Readonly<Record<string, { center: readonly [number, number], points: ReadonlyArray<readonly [number, number]> }>> = ' +
  JSON.stringify(collisionHulls) + '\n')

// Enough to cover every clip's keys, both ends of the aim, gaze apart from
// aim, a blink and every expression, without a huge file.
const OPTIONS = [
  {},
  { aimAngle: 60, blink: 0.5, expression: 'closed' },
  { aimAngle: -45, lookAngle: 20, expression: 'smile' },
  // Magnet's own magnet target, apart from the gun's aim; Peep ignores it.
  ...(robot === ROBOTS.magnet ? [{ aimAngle: 30, magnetAngle: -20 }] : [])
]
const round = (v) => Math.round(v * 1e6) / 1e6
const poses = []
for (const name of [...Object.keys(clips)]) {
  const duration = clips[name].duration
  // Twelfths of the clip as well for every robot after Peep: the fixed times
  // alone missed a changed swing keyframe at 0.40 s. Peep keeps its sampling:
  // regenerating its fixtures would take the drop's later shoot/swing
  // revision, which is not ported (CLAUDE.md, the Peep section).
  const dense = robot === ROBOTS.peep ? [] : Array.from({ length: 11 }, (_, k) => Math.round((k + 1) * duration / 12 * 1e6) / 1e6)
  const times = [0, 0.23, 0.52, 1.1, 1.7, duration, duration + 0.37, ...dense].filter((t, i, a) => a.indexOf(t) === i)
  for (const t of times) {
    for (const options of OPTIONS) {
      const { state, matrices } = animationPose(name, t, options)
      // Only the muzzle's bone: every drawn bone is covered by `corners`.
      const mz = matrices.muzzle
      const a = state.animation
      poses.push({
        name,
        t,
        options,
        muzzle: [mz.a, mz.b, mz.c, mz.d, mz.x, mz.y].map(round),
        eye: [state.eye.x, state.eye.y, state.eye.sx, state.eye.sy].map(round),
        animation: [a.height, a.flash, a.eyeOpacity].map(round),
        detached: a.detached,
        corners: drawnCorners(state, matrices).map((c) => c.map((v) => Math.round(v * 1e5) / 1e5))
      })
    }
  }
}
const fixtures = join(client, '..', 'services', 'battle-royale-server', 'src', 'utils', robot.fixtures)
writeFileSync(fixtures, JSON.stringify({ drop: drop.split('/').pop(), poses }) + '\n')
console.log(`hulls.ts: ${Object.keys(collisionHulls).length} hulls; fixtures: ${poses.length} poses`)
