/**
 * One private map for every private world (decision #60, task private-5;
 * Nick 2026-11-06: "make those 2 levels identical for all players").
 *
 * A private world (layers 01-02, one human, private-6) is built on the same
 * terrain and gates as every other: the valleys, the walls, the portals,
 * exits and pads out to layer 03, and the `hello` run encodings. NPCs, loot,
 * items and caches still spawn at random (`World.refillLayer`, Q1).
 *
 * **Same everywhere (Q2):** the map is generated from `PRIVATE_MAP_SEED`
 * through its own generator (`seeded`), never `Math.random`, so every
 * process (`WORKERS`, no sticky sessions) and every deploy builds the same
 * one, and the world's other draws are not shifted. It is generated by the
 * first private world a process builds, through the ordinary map code in the
 * `World` constructor (`WorldOptions.map`), and kept here as a template; every
 * later private world takes the template's objects. **A changed seed, a
 * changed generator (`valleys.ts`, `walls.ts`, `World.placeGate`) or a changed
 * `LAYERS` row the map reads (shares, gate counts) is a new map, and so a
 * release**; `privatemap.spec.ts` pins its digest so that can't happen quietly.
 *
 * **Shared read-only:** every private world holds the template's very Sets
 * and run arrays. The Sets are `FrozenSet`s, whose `add`/`delete`/`clear`
 * throw, and the run arrays are frozen, so a write anywhere fails loudly
 * instead of changing every private world at once. A `ReadonlySet` type would
 * not do: types are erased and the server is built by swc. `BLOCKED` (static
 * terrain plus per-world rocks, stones and bodies in one Map) is **copied**
 * per world from the template's terrain.
 */

/** The private map's seed. Changing it is a new map (and a release). */
export const PRIVATE_MAP_SEED = 0x5eed0060

/**
 * A Set that cannot be written after construction: `add`, `delete` and
 * `clear` throw. Reads are a plain Set's.
 */
export class FrozenSet<T> extends Set<T> {
  constructor (values: Iterable<T>) {
    super()
    for (const value of values) super.add(value)
  }

  add (_value: T): this {
    throw new TypeError('the private map is shared by every private world: it is read-only')
  }

  delete (_value: T): boolean {
    throw new TypeError('the private map is shared by every private world: it is read-only')
  }

  clear (): void {
    throw new TypeError('the private map is shared by every private world: it is read-only')
  }
}

/**
 * A deterministic generator in [0, 1) (mulberry32): the same seed gives the
 * same sequence on every machine and Node version (32-bit integer arithmetic
 * only).
 */
export function seeded (seed: number): () => number {
  let state = seed >>> 0
  return () => {
    state = (state + 0x6d2b79f5) >>> 0
    let t = state
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

/** A gate of the map: an exit (`to` undefined), a portal, or a pad out of the world (`pad`). */
export interface MapGate {
  tag: number
  to: number | undefined
  pad: boolean
  x: number
  y: number
}

/** What a private world takes from the template (`World` constructor). */
export interface MapTemplate {
  /** The map size, held tags and `padsUp` it was built for (`PrivateMap.key`). */
  key: string
  voids: ReadonlyMap<number, FrozenSet<number>>
  walls: ReadonlyMap<number, FrozenSet<number>>
  voidRuns: ReadonlyMap<number, readonly number[]>
  wallRuns: ReadonlyMap<number, readonly number[]>
  /** Static blocked cells per layer (void and wall), the base of each world's own `BLOCKED`. */
  terrain: ReadonlyMap<number, ReadonlyMap<number, null>>
  /** In the order they were placed, so every world's gates get the same ids. */
  gates: readonly MapGate[]
}

/**
 * The holder of one map: its seed, and its template once the first world
 * built on it has generated it (`World` constructor, `WorldOptions.map`).
 * A world asking for another size, other layers or other `padsUp` throws:
 * one holder is one map.
 */
export class PrivateMap {
  template: MapTemplate | undefined

  constructor (readonly seed: number) {}

  /** A fresh generator from the seed: one per generation, never shared. */
  random (): () => number {
    return seeded(this.seed)
  }

  static key (size: number, tags: readonly number[], padsUp: boolean): string {
    return `${size}|${[...tags].join(',')}|${padsUp ? 'up' : 'no-up'}`
  }

  /** Throw unless the template (if any) was built for `key`. */
  check (key: string): void {
    if (this.template !== undefined && this.template.key !== key) {
      throw new Error(`the private map was built for ${this.template.key}, not ${key}`)
    }
  }
}

/** The process's private map: every private world is built on it (private-6). */
export const PRIVATE_MAP = new PrivateMap(PRIVATE_MAP_SEED)
